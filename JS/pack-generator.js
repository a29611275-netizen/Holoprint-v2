/**
 * Generates a valid Minecraft Bedrock .mcpack (behavior pack)
 * that places the selected structure via Script API when
 * player interacts with Armor Stand while holding Netherite Ingot.
 */

function generateUUID() {
  return 'xxxxxxxx-xxxx-4xxx-yxxx-xxxxxxxxxxxx'.replace(/[xy]/g, c => {
    const r = Math.random() * 16 | 0;
    const v = c === 'x' ? r : (r & 0x3 | 0x8);
    return v.toString(16);
  });
}

function sanitizeName(name) {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9_]/g, '_')
    .replace(/_+/g, '_')
    .replace(/^_|_$/g, '')
    .slice(0, 48) || 'structure';
}

/**
 * Build the script that listens for Armor Stand + Netherite Ingot interaction
 */
function buildMainScript(config) {
  const { structureId, offsetX, offsetY, offsetZ, rotation } = config;

  return `import { world, system } from "@minecraft/server";

const STRUCTURE_ID = "${structureId}";
const OFFSET = { x: ${Number(offsetX) || 0}, y: ${Number(offsetY) || 0}, z: ${Number(offsetZ) || 0} };
const ROTATION = "${rotation || 'None'}";

world.afterEvents.playerInteractWithEntity.subscribe((event) => {
  try {
    const player = event.player;
    const entity = event.target;

    if (!entity || entity.typeId !== "minecraft:armor_stand") return;

    const equippable = player.getComponent("minecraft:equippable");
    if (!equippable) return;

    const mainhand = equippable.getEquipment("Mainhand");
    if (!mainhand || mainhand.typeId !== "minecraft:netherite_ingot") return;

    const dim = entity.dimension;
    const loc = entity.location;
    const placeLoc = {
      x: Math.floor(loc.x) + OFFSET.x,
      y: Math.floor(loc.y) + OFFSET.y,
      z: Math.floor(loc.z) + OFFSET.z
    };

    // Place the structure from the behavior pack
    world.structureManager.place(STRUCTURE_ID, dim, placeLoc, {
      rotation: ROTATION,
      includeEntities: true,
      includeBlocks: true
    });

    player.sendMessage("§a[HoloPrint+] Structure placed!");
    // Optional feedback particle / sound
    try {
      dim.spawnParticle("minecraft:endrod", placeLoc);
    } catch (e) {}
  } catch (err) {
    console.warn("[HoloPrint+] Place failed:", err);
    try {
      event.player.sendMessage("§c[HoloPrint+] Failed to place structure. Check Beta APIs is ON and structure exists.");
    } catch (e) {}
  }
});

system.run(() => {
  console.log("[HoloPrint+] Script loaded. Interact Armor Stand with Netherite Ingot to place: " + STRUCTURE_ID);
});
`;
}

/**
 * Create the full .mcpack as a Blob
 * @param {Object} options
 * @param {Array} options.structures - array of { displayName, buffer }
 * @param {string} options.primaryId - structure identifier for script
 * @param {string} options.packName
 * @param {string} options.description
 * @param {number} options.offsetX/Y/Z
 * @param {string} options.rotation
 * @param {ArrayBuffer|null} options.iconBuffer
 */
async function generateMcpack(options) {
  const {
    structures,
    primaryStructure,
    packName,
    description,
    offsetX,
    offsetY,
    offsetZ,
    rotation,
    iconBuffer
  } = options;

  if (!structures.length) throw new Error('No structures provided');
  if (!primaryStructure) throw new Error('No primary structure selected');

  const zip = new JSZip();
  const headerUUID = generateUUID();
  const moduleUUID = generateUUID();
  const scriptUUID = generateUUID();

  const namespace = 'holoprint';
  const primarySafe = sanitizeName(primaryStructure.displayName);
  const structureId = `${namespace}:${primarySafe}`;

  // Manifest
  const manifest = {
    format_version: 2,
    header: {
      name: packName || 'HoloPrint+ Pack',
      description: (description || 'Generated by HoloPrint+') + '\n\nPlace Armor Stand, hold Netherite Ingot, interact to place structure.\nRequires Beta APIs experiment.',
      uuid: headerUUID,
      version: [1, 0, 0],
      min_engine_version: [1, 21, 0]
    },
    modules: [
      {
        type: 'data',
        uuid: moduleUUID,
        version: [1, 0, 0]
      },
      {
        type: 'script',
        language: 'javascript',
        uuid: scriptUUID,
        version: [1, 0, 0],
        entry: 'scripts/main.js'
      }
    ],
    dependencies: [
      {
        module_name: '@minecraft/server',
        version: '1.16.0'
      }
    ]
  };

  zip.file('manifest.json', JSON.stringify(manifest, null, 2));

  // Script
  const script = buildMainScript({
    structureId,
    offsetX,
    offsetY,
    offsetZ,
    rotation
  });
  zip.file('scripts/main.js', script);

  // Structures
  for (const s of structures) {
    const safe = sanitizeName(s.displayName);
    const path = `structures/${namespace}/${safe}.mcstructure`;
    const buf = s.buffer || await StructureStore.loadBuffer(s);
    zip.file(path, buf);
  }

  // Pack icon (optional)
  if (iconBuffer) {
    zip.file('pack_icon.png', iconBuffer);
  }

  // Generate blob
  const blob = await zip.generateAsync({
    type: 'blob',
    compression: 'DEFLATE',
    compressionOptions: { level: 6 }
  });

  const filename = sanitizeName(packName || 'holoprint_plus') + '.mcpack';
  return { blob, filename, structureId, manifest };
}

// Expose
window.PackGenerator = { generateMcpack, sanitizeName, generateUUID };
